CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) UNIQUE,
    email VARCHAR(255),
    password VARCHAR(255),
    phone VARCHAR(255),
    role VARCHAR(255),
    profile_image_path VARCHAR(255)
);

CREATE TABLE tickets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255),
    description TEXT,
    status VARCHAR(255),
    priority VARCHAR(255),
    user_id BIGINT NOT NULL,
    assigned_to_id BIGINT,
    assigned_by_id BIGINT,
    project_id BIGINT NOT NULL,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT fk_tickets_created_by FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_tickets_assigned_to FOREIGN KEY (assigned_to_id) REFERENCES users (id),
    CONSTRAINT fk_tickets_assigned_by FOREIGN KEY (assigned_by_id) REFERENCES users (id),
    CONSTRAINT fk_tickets_project FOREIGN KEY (project_id) REFERENCES projects (id)
);

CREATE TABLE comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content TEXT,
    ticket_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    timestamp TIMESTAMP,
    CONSTRAINT fk_comments_ticket FOREIGN KEY (ticket_id) REFERENCES tickets (id),
    CONSTRAINT fk_comments_author FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_tickets_assigned_to ON tickets (assigned_to_id);
CREATE INDEX idx_tickets_project ON tickets (project_id);
CREATE INDEX idx_tickets_status ON tickets (status);
CREATE INDEX idx_comments_ticket ON comments (ticket_id);
